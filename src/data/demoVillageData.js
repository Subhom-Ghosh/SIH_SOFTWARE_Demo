// Center around Kalyanpur Village: 25.3210° N, 82.9650° E
const BASE_LAT = 25.3210;
const BASE_LNG = 82.9650;

// Helper to create contiguous parcel geometries
function makeRect(r, c, w = 0.0012, h = 0.0009, jitter = 0) {
  const x0 = BASE_LNG + c * 0.0013 + (Math.sin(r * 3 + c) * 0.0001) + jitter;
  const y0 = BASE_LAT + r * 0.0010 + (Math.cos(r + c * 2) * 0.00008) + jitter;
  const x1 = x0 + w + (Math.sin(r) * 0.00006);
  const y1 = y0;
  const x2 = x0 + w + (Math.cos(c) * 0.00005);
  const y2 = y0 + h + (Math.sin(c) * 0.00004);
  const x3 = x0;
  const y3 = y0 + h;
  return [[[x0, y0], [x1, y1], [x2, y2], [x3, y3], [x0, y0]]];
}

// Generate surveyed geometry with realistic slight deviations or intentional mismatches
function makeSurveyedRect(r, c, type) {
  const base = makeRect(r, c);
  const ring = base[0];
  let p0 = [...ring[0]];
  let p1 = [...ring[1]];
  let p2 = [...ring[2]];
  let p3 = [...ring[3]];

  if (type === 'match') {
    // 0.5 meter precision
    return [[[p0[0], p0[1]], [p1[0], p1[1]], [p2[0], p2[1]], [p3[0], p3[1]], [p0[0], p0[1]]]];
  } else if (type === 'area_shrink') {
    // 8-12% shrink in width (e.g. soil erosion / canal bund encroachment)
    p1[0] = p1[0] - 0.00018;
    p2[0] = p2[0] - 0.00017;
    return [[[p0[0], p0[1]], [p1[0], p1[1]], [p2[0], p2[1]], [p3[0], p3[1]], [p0[0], p0[1]]]];
  } else if (type === 'encroach') {
    // Protrudes 15 meters north into adjacent road or pasture
    p2[1] = p2[1] + 0.00022;
    p3[1] = p3[1] + 0.00024;
    return [[[p0[0], p0[1]], [p1[0], p1[1]], [p2[0], p2[1]], [p3[0], p3[1]], [p0[0], p0[1]]]];
  } else if (type === 'boundary_shift') {
    // Trapezoidal skew
    p0[0] = p0[0] + 0.00012;
    p1[1] = p1[1] - 0.00014;
    p2[0] = p2[0] + 0.00015;
    return [[[p0[0], p0[1]], [p1[0], p1[1]], [p2[0], p2[1]], [p3[0], p3[1]], [p0[0], p0[1]]]];
  } else {
    // expansion
    p1[0] = p1[0] + 0.00016;
    p2[0] = p2[0] + 0.00016;
    return [[[p0[0], p0[1]], [p1[0], p1[1]], [p2[0], p2[1]], [p3[0], p3[1]], [p0[0], p0[1]]]];
  }
}

